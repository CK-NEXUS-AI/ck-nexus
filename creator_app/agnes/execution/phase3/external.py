from __future__ import annotations

from typing import Protocol


class ExternalWorkspaceAdapter(Protocol):
    name: str

    async def create(self, *, baseline_commit: str, execution_id: str) -> dict: ...
    async def execute(self, *, workspace_id: str, command: list[str]) -> dict: ...
    async def collect(self, *, workspace_id: str) -> dict: ...
    async def discard(self, *, workspace_id: str) -> None: ...
    async def health(self) -> dict: ...
